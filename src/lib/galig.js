// Хангыл → монгол кирилл галиг (ойролцоо дуудлага). Эхлэгчид унших тулгуур болгох зорилготой —
// бүх дуудлагын дүрмийг биш, хамгийн их тохиолддог хоёрыг тусгана:
//   1) холбох: 한국어 → хан-гу-гө (төгсгөлийн гийгүүлэгч дараагийн ㅇ руу шилжинэ)
//   2) хамраар дуудах: 합니다 → хам-ни-да, 한국말 → хан-гуң-мал

const INI = ["г", "кк", "н", "д", "тт", "р", "м", "б", "пп", "с", "сс", "", "ж", "зз", "ч", "к", "т", "п", "х"];
const VOW = ["а", "э", "я", "е", "ө", "э", "йө", "е", "о", "ва", "вэ", "вэ", "ё", "у", "вө", "вэ", "ви", "ю", "ы", "ый", "и"];
// Төгсгөлийн 28 хэлбэр (0 = байхгүй) → [дуудлага, ㅇ-ийн өмнө шилжих гийгүүлэгчийн эхний индекс, үлдэх хэсэг]
const FIN = [
  ["", -1, ""], ["к", 0, ""], ["к", 1, ""], ["к", 9, "к"], ["н", 2, ""], ["н", 12, "н"], ["н", 2, ""],
  ["т", 3, ""], ["л", 5, ""], ["к", 0, "л"], ["м", 6, "л"], ["л", 7, "л"], ["л", 9, "л"], ["л", 16, "л"],
  ["п", 17, "л"], ["л", 5, ""], ["м", 6, ""], ["п", 7, ""], ["п", 9, "п"], ["т", 9, ""], ["т", 10, ""],
  ["нг", -1, "нг"], ["т", 12, ""], ["т", 14, ""], ["к", 15, ""], ["т", 16, ""], ["п", 17, ""], ["т", 11, ""], // ㅎ: эгшгийн өмнө дуудагдахгүй
];

function parts(ch) {
  const c = ch.charCodeAt(0) - 0xac00;
  if (c < 0 || c > 11171) return null;
  return { i: Math.floor(c / 588), v: Math.floor((c % 588) / 28), f: c % 28 };
}

/** "한국어를 공부합니다" → "хангугөрыл гонгбухамнида" */
export function galig(text) {
  if (!text) return "";
  const chars = [...text];
  const sy = chars.map(parts);
  let out = "";
  for (let k = 0; k < chars.length; k++) {
    const p = sy[k];
    if (!p) {
      out += chars[k];
      continue;
    }
    let ini = INI[p.i];
    // Өмнөх үе төгсгөлөө энэ ㅇ руу шилжүүлсэн бол (холбох).
    if (p.i === 11 && k > 0 && sy[k - 1] && sy[k - 1].f && FIN[sy[k - 1].f][1] >= 0) ini = INI[FIN[sy[k - 1].f][1]];
    // ㄹ үгийн дунд эгшгийн дараа «р», хоёр ㄹ дараалбал «лл».
    if (p.i === 5 && k > 0 && sy[k - 1]?.f === 8) ini = "л";

    let vow = VOW[p.v];
    if (p.v === 6 && p.i !== 11) vow = "ё"; // 녕 → нён, харин 여 → йө

    let fin = FIN[p.f][0];
    const next = sy[k + 1];
    if (p.f && next) {
      if (next.i === 11 && FIN[p.f][1] >= 0) fin = FIN[p.f][2];
      else if (next.i === 2 || next.i === 6) {
        // хамраар дуудах: ㅂ→м, ㄱ→нг, ㄷ/ㅅ/ㅈ…→н
        if (fin === "п") fin = "м";
        else if (fin === "к") fin = "нг";
        else if (fin === "т") fin = "н";
      }
    }
    out += ini + vow + fin;
  }
  return out;
}
